'use strict';
const assert = require('node:assert/strict');
const test = require('node:test');
const summary = require('../.github/scripts/summarize-pr-checks.cjs');

const owner = 'NatesHonor';
const repo = 'MissionchiefBot-X';
const sha = '833dc880f4c9fd9b3df9534c81f073c48ca11897';

const check = (id, name, conclusion, extra = {}) => ({
  id, name, status: conclusion === null ? 'in_progress' : 'completed', conclusion,
  started_at: `2026-10-27T18:40:${String(id % 60).padStart(2, '0')}Z`,
  html_url: `https://github.com/${owner}/${repo}/runs/${id}`, ...extra,
});

test('every check is counted, not a fixed list of CI jobs', () => {
  const runs = Array.from({length: 24}, (_, index) => check(index + 1, `check ${index + 1}`, 'success'));
  runs[3] = check(4, 'Validate PR description', 'failure');
  runs[4] = check(5, 'CodeQL', 'failure', {app: {slug: 'github-advanced-security'}});
  const checks = summary.latestChecks(runs);
  const body = summary.commentBody({checks, analyses: new Map(), owner, repo, sha});
  assert.equal(checks.length, 24);
  assert.match(body, /\*\*22\/24\*\* checks passed · \*\*2 failed\*\*/);
  assert.match(body, /### Why checks failed/);
  assert.ok(body.startsWith(summary.MARKER));
});

test('no AI or OpenHands attribution in the comment', () => {
  const checks = summary.latestChecks([check(1, 'lint (ruff)', 'success')]);
  const body = summary.commentBody({checks, analyses: new Map(), owner, repo, sha});
  assert.doesNotMatch(body, /OpenHands|AI agent|generated by/i);
  assert.match(body, /All checks passed/);
});

test('re-runs keep only the newest result and the summary job is excluded', () => {
  const checks = summary.latestChecks([
    check(1, 'lint (ruff)', 'failure'),
    check(9, 'lint (ruff)', 'success'),
    check(3, summary.SELF, 'success'),
    check(4, 'CodeQL', null),
  ]);
  assert.deepEqual(checks.map(item => [item.name, summary.stateOf(item)]),
    [['CodeQL', 'pending'], ['lint (ruff)', 'success']]);
  const body = summary.commentBody({checks, analyses: new Map(), owner, repo, sha});
  assert.match(body, /\*\*1\/2\*\* checks passed · \*\*1 still running\*\*/);
  assert.doesNotMatch(body, /All checks passed/);
});

test('failed checks are listed first', () => {
  const checks = summary.latestChecks([check(1, 'a passing', 'success'), check(2, 'z failing', 'failure')]);
  const body = summary.commentBody({checks, analyses: new Map(), owner, repo, sha});
  assert.ok(body.indexOf('z failing') < body.indexOf('a passing'));
});

test('error lines are pulled from a job log without script noise', () => {
  const log = [
    '2026-10-27T18:40:53.4863888Z ##[group]Run actions/github-script@v7',
    "2026-10-27T18:40:53.4863888Z if (errors.length) {",
    '2026-10-27T18:40:53.4866799Z   retry-exempt-status-codes: 400,401,403,404,422',
    '2026-10-27T18:40:53.8022560Z ##[error]Add at least 20 characters to `## Summary` or `## What changed`.',
    'Add your validation steps to `## Testing`, `## Test plan`, or `## Validation`.',
    '2026-10-27T18:40:53.8666831Z ##[warning]Node.js 20 is deprecated. The following actions target Node.js 20',
    '2026-10-27T18:40:54.0000000Z core/bot.py:12:5: F821 undefined name `foo`',
    '2026-10-27T18:40:54.0000000Z FAILED tests/test_x.py::test_y - AssertionError: boom',
  ].join('\n');
  const lines = summary.errorLines(log);
  assert.deepEqual(lines, [
    'Add at least 20 characters to `## Summary` or `## What changed`.',
    'core/bot.py:12:5: F821 undefined name `foo`',
    'FAILED tests/test_x.py::test_y - AssertionError: boom',
  ]);
});

test('analysis explains the failure, the failing step and how to fix it', () => {
  const failed = check(7, 'Validate PR description', 'failure');
  const text = summary.analysisFor(failed, {
    steps: ['Check required description sections'],
    annotations: [{annotation_level: 'failure', path: '.github',
      message: 'Add at least 20 characters to `## Summary` or `## What changed`.\nAdd your validation steps to `## Testing`.'}],
    logLines: ['Add at least 20 characters to `## Summary`'],
  });
  assert.match(text, /\*\*Failed step:\*\* `Check required description sections`/);
  assert.match(text, /- Add at least 20 characters to `## Summary`/);
  assert.match(text, /- Add your validation steps to `## Testing`/);
  assert.doesNotMatch(text, /`\.github`/);
  assert.match(text, /\*\*How to fix:\*\* Fill in `## Summary`/);
  assert.match(text, /Error output from the log/);
});

test('analysis falls back to check output, then to a clear message', () => {
  const codeql = check(8, 'CodeQL', 'failure', {output: {title: '1 new alert', summary: 'Uncontrolled command line'}});
  assert.match(summary.analysisFor(codeql, {}), /\*\*Why it failed:\*\* 1 new alert — Uncontrolled command line/);
  assert.match(summary.analysisFor(codeql, {}), /Open the CodeQL alert/);
  const cancelled = check(9, 'compatibility', 'cancelled');
  assert.match(summary.analysisFor(cancelled, {}), /was cancelled/);
});

test('log text cannot break the code block or mention users', () => {
  const text = summary.analysisFor(check(1, 'lint (ruff)', 'failure'), {logLines: ['```', 'error from @someone']});
  assert.equal(text.match(/```/g).length, 2);
  assert.doesNotMatch(text, /@someone/);
});

test('hints cover the repository checks', () => {
  for (const name of ['Validate PR description', 'Lint PR title (conventional)', 'Release contract',
    'Check PR artifacts', 'CodeQL', 'Dependency review', 'dependency-audit', 'secret-scan (gitleaks)',
    'security (bandit)', 'lint (ruff)', 'type-check (mypy)', 'compatibility', 'test (release notifications)']) {
    assert.doesNotMatch(summary.hintFor(name), /Open the details link/, name);
  }
});

test('pull request is found for fork runs with no attached PRs', async () => {
  const github = {
    paginate: async fn => fn(),
    rest: {
      repos: {listPullRequestsAssociatedWithCommit: () => []},
      pulls: {list: () => [{number: 92, head: {sha}}]},
    },
  };
  assert.equal(await summary.findPullRequest({github, owner, repo, run: {head_sha: sha, pull_requests: []}}), 92);
  assert.equal(await summary.findPullRequest({github, owner, repo,
    run: {head_sha: sha, pull_requests: [{number: 5, base: {repo: {name: repo}}}]}}), 5);
});
